def strip_pointer_block(content: str) -> str:
    """Remove the auto-generated pointer block if present."""
    start_idx = content.find("<!-- BEGIN CANONICAL RULES POINTER")
    end_tag = "<!-- END CANONICAL RULES POINTER -->"
    end_idx = content.find(end_tag)
    if start_idx != -1 and end_idx != -1:
        cleaned = content[:start_idx] + content[end_idx + len(end_tag) :]
        return cleaned.strip() + "\n"
    return content


def strip_gitignore_block(content: str) -> str:
    """Remove the auto-generated gitignore block if present."""
    start_idx = content.find(GITIGNORE_START_TAG)
    end_idx = content.find(GITIGNORE_END_TAG)
    if start_idx != -1 and end_idx != -1:
        cleaned = content[:start_idx] + content[end_idx + len(GITIGNORE_END_TAG) :]
        return cleaned.strip() + ("\n" if cleaned.strip() else "")
    return content


def _extract_existing_gitignore_block_entries(content: str) -> list[str]:
    """Extract existing entries inside the managed gitignore block if present."""
    start_idx = content.find(GITIGNORE_START_TAG)
    end_idx = content.find(GITIGNORE_END_TAG)
    if start_idx == -1 or end_idx == -1 or end_idx < start_idx:
        return []
    block_body = content[start_idx + len(GITIGNORE_START_TAG) : end_idx]
    return [
        line.strip()
        for line in block_body.splitlines()
        if line.strip() and not line.strip().startswith("#")
    ]


def collect_gitignore_entries(
    root_dir: Path,
    include_antigravity: bool | None = None,
    include_claude: bool | None = None,
    include_agents_md: bool | None = None,
) -> list[str]:
    """Collect relative paths for ported scripts, generated assistant files, and runtime state."""
    entries: list[str] = list(PORTED_TOOLING_SCRIPTS)

    if (root_dir / "README_TOOLING.md").is_file():
        entries.append("README_TOOLING.md")
    if (root_dir / "AGENTS.md.dist").is_file():
        entries.append("AGENTS.md.dist")

    if include_antigravity is None:
        include_antigravity = (
            (root_dir / ".agents" / "hooks.json").exists()
            or (root_dir / ".agents" / "skills" / "code-auditor").exists()
            or (root_dir / ".agents" / "skills" / "personal-preferences").exists()
        )
    if include_antigravity:
        entries.extend(ANTIGRAVITY_GITIGNORE_ENTRIES)

    if include_claude is None:
        include_claude = (
            (root_dir / ".claude" / "commands").exists()
            or (root_dir / ".claude" / "skills").exists()
        )
    if include_claude:
        entries.extend(CLAUDE_GITIGNORE_ENTRIES)

    if include_agents_md is None:
        agents_file = find_existing_file(root_dir, ("AGENTS.md", "agents.md"))
        if agents_file and agents_file.is_file():
            cleaned = strip_pointer_block(agents_file.read_text(encoding="utf-8")).strip()
            include_agents_md = cleaned in (
                "",
                "# Human-Agent Collaboration Protocol & Repository Guidelines",
            )
        else:
            include_agents_md = False
    if include_agents_md:
        agents_file = find_existing_file(root_dir, ("AGENTS.md", "agents.md"))
        entries.append(agents_file.name if agents_file else "AGENTS.md")

    entries.extend(RUNTIME_STATE_GITIGNORE_ENTRIES)

    # Deduplicate while preserving order
    deduped: list[str] = []
    seen: set[str] = set()
    for item in entries:
        if item not in seen:
            seen.add(item)
            deduped.append(item)
    return deduped


def update_gitignore(
    root_dir: Path,
    entries: Sequence[str] | None = None,
    include_antigravity: bool | None = None,
    include_claude: bool | None = None,
    include_agents_md: bool | None = None,
) -> bool:
    """Add or update the managed tooling block in .gitignore."""
    gitignore_file = root_dir / ".gitignore"
    existing_content = gitignore_file.read_text(encoding="utf-8") if gitignore_file.is_file() else ""
    previous_block_entries = _extract_existing_gitignore_block_entries(existing_content)

    resolved_entries = (
        list(entries)
        if entries is not None
        else collect_gitignore_entries(
            root_dir,
            include_antigravity=include_antigravity,
            include_claude=include_claude,
            include_agents_md=include_agents_md,
        )
    )

    merged_entries: list[str] = []
    seen: set[str] = set()
    for item in [*previous_block_entries, *resolved_entries]:
        if item not in seen:
            seen.add(item)
            merged_entries.append(item)

    block_lines = [GITIGNORE_START_TAG, *merged_entries, GITIGNORE_END_TAG]
    block_text = "\n".join(block_lines)

    base_content = strip_gitignore_block(existing_content).rstrip()
    new_content = f"{base_content}\n\n{block_text}\n" if base_content else f"{block_text}\n"
    gitignore_file.write_text(new_content, encoding="utf-8")
    print(f"✅ Updated .gitignore with installed tooling paths -> {gitignore_file}")
    return True


def install_git_hook(root_dir: Path) -> bool:
    """Install git pre-commit hook."""
    git_hooks_dir = root_dir / ".git" / "hooks"
    if not git_hooks_dir.exists():
        print(f"Skipping Git hook: {git_hooks_dir} not found (not a git root).")
        return False

    hook_file = git_hooks_dir / "pre-commit"
    hook_file.write_text(GIT_HOOK_TEMPLATE, encoding="utf-8")
    current_mode = hook_file.stat().st_mode
    hook_file.chmod(current_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    print(f"✅ Installed Git pre-commit hook -> {hook_file}")
    return True


