def ensure_agents_file(root_dir: Path, assume_yes: bool = False) -> bool:
    """Ensure AGENTS.md (or agents.md) exists and contains canonical rules pointer."""
    agents_file = find_existing_file(root_dir, ("AGENTS.md", "agents.md"))
    if agents_file and agents_file.is_file():
        content = agents_file.read_text(encoding="utf-8")
        if "BEGIN CANONICAL RULES POINTER" in content:
            print(f"ℹ️  Canonical rules pointer already present in {agents_file.name}")
            return True
        if content.strip():
            if not ask_permission(agents_file, assume_yes=assume_yes):
                print(f"⏭️  Skipped adding pointer to {agents_file.name} (permission denied).")
                return False
            new_content = content.rstrip() + "\n\n" + AGENTS_MEMORY_POINTER_BLOCK + "\n"
            agents_file.write_text(new_content, encoding="utf-8")
            print(f"✅ Inserted canonical rules pointer into {agents_file.name}")
            return True
        else:
            agents_file.write_text(DEFAULT_AGENTS_TEMPLATE.strip() + "\n", encoding="utf-8")
            print(f"✅ Initialized empty {agents_file.name} with canonical rules pointer")
            return True
    else:
        agents_file = root_dir / "AGENTS.md"
        agents_file.write_text(DEFAULT_AGENTS_TEMPLATE.strip() + "\n", encoding="utf-8")
        print(f"✅ Created {agents_file.name} with canonical rules pointer")
        return True


def install_claude(root_dir: Path, assume_yes: bool = False) -> bool:
    """Install Claude Code commands, prepackaged skills, Git pre-commit hook, and update existing CLAUDE.md if present."""
    install_git_hook(root_dir)
    ensure_tiered_rule_directories(root_dir)

    commands_dir = root_dir / ".claude" / "commands"
    commands_dir.mkdir(parents=True, exist_ok=True)

    audit_command_file = commands_dir / "audit.md"
    audit_command_file.write_text(CLAUDE_AUDIT_COMMAND_TEMPLATE, encoding="utf-8")

    pref_command_file = commands_dir / "preferences.md"
    pref_command_file.write_text(CLAUDE_PREFERENCES_COMMAND_TEMPLATE, encoding="utf-8")

    print(f"✅ Installed Claude Code command -> {audit_command_file}")
    print(f"✅ Installed Claude Code command -> {pref_command_file}")

    audit_skill_dir = root_dir / ".claude" / "skills" / "code-auditor"
    audit_skill_dir.mkdir(parents=True, exist_ok=True)
    audit_skill_file = audit_skill_dir / "SKILL.md"
    audit_skill_file.write_text(AUDIT_SKILL_TEMPLATE, encoding="utf-8")

    pref_skill_dir = root_dir / ".claude" / "skills" / "personal-preferences"
    pref_skill_dir.mkdir(parents=True, exist_ok=True)
    pref_skill_file = pref_skill_dir / "SKILL.md"
    pref_skill_file.write_text(PREFERENCES_SKILL_TEMPLATE, encoding="utf-8")

    print(f"✅ Installed Claude Code skill -> {audit_skill_file}")
    print(f"✅ Installed Claude Code skill -> {pref_skill_file}")

    claude_file = find_existing_file(root_dir, ("CLAUDE.md", "claude.md"))
    if claude_file and claude_file.is_file():
        content = claude_file.read_text(encoding="utf-8")
        if "BEGIN CANONICAL RULES POINTER" in content:
            print(f"ℹ️  Canonical rules pointer already present in {claude_file.name}")
        elif content.strip():
            if not ask_permission(claude_file, assume_yes=assume_yes):
                print(f"⏭️  Skipped adding pointer to {claude_file.name} (permission denied).")
            else:
                new_content = content.rstrip() + "\n\n" + CLAUDE_MEMORY_POINTER_BLOCK + "\n"
                claude_file.write_text(new_content, encoding="utf-8")
                print(f"✅ Inserted canonical rules pointer into {claude_file.name}")
        else:
            claude_file.write_text("# Claude Memory\n\n" + CLAUDE_MEMORY_POINTER_BLOCK + "\n", encoding="utf-8")
            print(f"✅ Initialized empty {claude_file.name} with canonical rules pointer")
    else:
        print("ℹ️  No CLAUDE.md found. Claude Code will automatically fall back to AGENTS.md (no CLAUDE.md created).")

    return True


def clean_tooling(root_dir: Path) -> None:
    """Remove generated assistant artifacts and pointers."""
    git_hook = root_dir / ".git" / "hooks" / "pre-commit"
    if git_hook.exists():
        git_hook.unlink()
        print(f"🗑️  Removed {git_hook}")

    ag_audit_skill = root_dir / ".agents" / "skills" / "code-auditor" / "SKILL.md"
    if ag_audit_skill.exists():
        ag_audit_skill.unlink()
        print(f"🗑️  Removed {ag_audit_skill}")
    ag_audit_dir = root_dir / ".agents" / "skills" / "code-auditor"
    if ag_audit_dir.exists() and not any(ag_audit_dir.iterdir()):
        ag_audit_dir.rmdir()

    ag_pref_skill = root_dir / ".agents" / "skills" / "personal-preferences" / "SKILL.md"
    if ag_pref_skill.exists():
        ag_pref_skill.unlink()
        print(f"🗑️  Removed {ag_pref_skill}")
    ag_pref_dir = root_dir / ".agents" / "skills" / "personal-preferences"
    if ag_pref_dir.exists() and not any(ag_pref_dir.iterdir()):
        ag_pref_dir.rmdir()

    ag_hooks = root_dir / ".agents" / "hooks.json"
    if ag_hooks.exists():
        ag_hooks.unlink()
        print(f"🗑️  Removed {ag_hooks}")

    claude_audit_cmd = root_dir / ".claude" / "commands" / "audit.md"
    if claude_audit_cmd.exists():
        claude_audit_cmd.unlink()
        print(f"🗑️  Removed {claude_audit_cmd}")

    claude_pref_cmd = root_dir / ".claude" / "commands" / "preferences.md"
    if claude_pref_cmd.exists():
        claude_pref_cmd.unlink()
        print(f"🗑️  Removed {claude_pref_cmd}")

    claude_cmd_dir = root_dir / ".claude" / "commands"
    if claude_cmd_dir.exists() and not any(claude_cmd_dir.iterdir()):
        claude_cmd_dir.rmdir()

    claude_audit_skill = root_dir / ".claude" / "skills" / "code-auditor" / "SKILL.md"
    if claude_audit_skill.exists():
        claude_audit_skill.unlink()
        print(f"🗑️  Removed {claude_audit_skill}")
    claude_audit_dir = root_dir / ".claude" / "skills" / "code-auditor"
    if claude_audit_dir.exists() and not any(claude_audit_dir.iterdir()):
        claude_audit_dir.rmdir()

    claude_pref_skill = root_dir / ".claude" / "skills" / "personal-preferences" / "SKILL.md"
    if claude_pref_skill.exists():
        claude_pref_skill.unlink()
        print(f"🗑️  Removed {claude_pref_skill}")
    claude_pref_dir = root_dir / ".claude" / "skills" / "personal-preferences"
    if claude_pref_dir.exists() and not any(claude_pref_dir.iterdir()):
        claude_pref_dir.rmdir()

    claude_skills_dir = root_dir / ".claude" / "skills"
    if claude_skills_dir.exists() and not any(claude_skills_dir.iterdir()):
        claude_skills_dir.rmdir()

    claude_dir = root_dir / ".claude"
    if claude_dir.exists() and not any(claude_dir.iterdir()):
        claude_dir.rmdir()

    # Clean CLAUDE.md / claude.md
    claude_file = find_existing_file(root_dir, ("CLAUDE.md", "claude.md"))
    if claude_file and claude_file.exists():
        content = claude_file.read_text(encoding="utf-8")
        if "BEGIN CANONICAL RULES POINTER" in content:
            cleaned = strip_pointer_block(content)
            if cleaned.strip() in ("", "# Claude Memory"):
                claude_file.unlink()
                print(f"🗑️  Removed {claude_file.name}")
            else:
                claude_file.write_text(cleaned, encoding="utf-8")
                print(f"🗑️  Cleaned pointer in {claude_file.name} (preserved user memory)")

    # Clean AGENTS.md / agents.md
    agents_file = find_existing_file(root_dir, ("AGENTS.md", "agents.md"))
    if agents_file and agents_file.exists():
        content = agents_file.read_text(encoding="utf-8")
        if "BEGIN CANONICAL RULES POINTER" in content:
            cleaned = strip_pointer_block(content)
            if cleaned.strip() in (
                "",
                "# Human-Agent Collaboration Protocol & Repository Guidelines",
                "# Agent Collaboration Guidelines",
                "# Agents",
            ):
                agents_file.unlink()
                print(f"🗑️  Removed empty template {agents_file.name}")
            else:
                agents_file.write_text(cleaned, encoding="utf-8")
                print(f"🗑️  Cleaned pointer in {agents_file.name} (preserved user guidelines)")

    # Clean managed block in .gitignore
    gitignore_file = root_dir / ".gitignore"
    if gitignore_file.is_file():
        content = gitignore_file.read_text(encoding="utf-8")
        if GITIGNORE_START_TAG in content:
            cleaned = strip_gitignore_block(content)
            if not cleaned.strip():
                gitignore_file.unlink()
                print(f"🗑️  Removed empty {gitignore_file.name}")
            else:
                gitignore_file.write_text(cleaned, encoding="utf-8")
                print(f"🗑️  Cleaned tooling entries from {gitignore_file.name} (preserved user rules)")

    # Clean managed block in .env.example
    env_example_file = root_dir / ".env.example"
    if env_example_file.is_file():
        content = env_example_file.read_text(encoding="utf-8")
        if ENV_BLOCK_START_TAG in content:
            cleaned = strip_env_block(content)
            if not cleaned.strip():
                env_example_file.unlink()
                print(f"🗑️  Removed empty {env_example_file.name}")
            else:
                env_example_file.write_text(cleaned, encoding="utf-8")
                print(f"🗑️  Cleaned agentic-dev block from {env_example_file.name} (preserved user template)")


def _configure_env_sync_url(root_dir: Path, sync_url: str) -> Path:
    """Create or non-destructively merge .env in root_dir with ORG_RULES_SYNC_URL."""
    env_file = root_dir / ".env"
    _, colliding_keys = merge_env_file(
        env_file,
        overrides={"ORG_RULES_SYNC_URL": f'"{sync_url}"'},
    )
    if colliding_keys:
        print(
            f"ℹ️  Preserved existing key(s) in {env_file.name}: {', '.join(colliding_keys)}"
        )
    os.environ["ORG_RULES_SYNC_URL"] = sync_url
    print(f"✅ Configured ORG_RULES_SYNC_URL in {env_file}")
    return env_file


def run_init_wizard(
    root_dir: Path,
    ask_gitignore: bool = True,
) -> tuple[dict[str, bool], bool | None]:
    """Run interactive 3-step installation wizard for `agentic-dev init`."""
    print("\n🧙 Agentic Dev Interactive Setup Wizard")
    print("=" * 60)
    print(f"Target Workspace: {root_dir}")

    # Step 1: Select coding assistant(s)
    print("\n[Step 1/3] Select coding assistant(s) to configure:")
    print("  1) All supported assistants (Antigravity + Claude Code + AGENTS.md + Git Hook) [default]")
    print("  2) Antigravity only (.agents/skills, .agents/hooks.json, AGENTS.md, Git Hook)")
    print("  3) Claude Code only (.claude/commands, .claude/skills, AGENTS.md, Git Hook)")
    print("  4) Minimal (Git Pre-Commit Hook + AGENTS.md only)")

    try:
        choice = input("Choose option [1-4] (default: 1): ").strip() or "1"
    except (EOFError, KeyboardInterrupt):
        print("\nWizard cancelled by user.")
        choice = "1"

    selection = {
        "all": False,
        "antigravity": False,
        "claude": False,
        "agents": True,
        "git_hook": True,
    }
    if choice == "2":
        selection["antigravity"] = True
    elif choice == "3":
        selection["claude"] = True
    elif choice == "4":
        pass
    else:
        selection["all"] = True

    # Step 2: Configure .env & Dynamic Org Rules Sync URL
    print("\n[Step 2/3] Configure .env and Organizational Rules Sync:")
    print(f"  Default URL: {DEFAULT_SAMPLE_ORG_RULES_URL}")
    try:
        url_resp = input(
            "Enter ORG_RULES_SYNC_URL [press Enter for default, or 'skip' to skip]: "
        ).strip()
    except (EOFError, KeyboardInterrupt):
        print("\nSkipping ORG_RULES_SYNC_URL configuration.")
        url_resp = "skip"

    if url_resp.lower() not in ("skip", "n", "no", "none"):
        chosen_url = url_resp if url_resp else DEFAULT_SAMPLE_ORG_RULES_URL
        _configure_env_sync_url(root_dir, chosen_url)
    else:
        print("⏭️  Skipped .env ORG_RULES_SYNC_URL setup.")

    # Step 3: .gitignore preference
    gitignore_pref: bool | None = None
    if ask_gitignore:
        print("\n[Step 3/3] Git Ignore Configuration:")
        try:
            gi_resp = (
                input(
                    "Would you like to add the generated assistant configs and runtime state to .gitignore? [y/N]: "
                )
                .strip()
                .lower()
            )
            gitignore_pref = gi_resp in ("y", "yes")
        except (EOFError, KeyboardInterrupt):
            print("\nSkipping .gitignore update.")
            gitignore_pref = False

    print("=" * 60 + "\n")
    return selection, gitignore_pref


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Dynamic Assistant Tooling Installer")
    parser.add_argument("--all", action="store_true", help="Install all tooling, hooks, and guidelines")
    parser.add_argument("--git-hook", action="store_true", help="Install Git pre-commit hook")
    parser.add_argument("--antigravity", action="store_true", help="Install Antigravity skills & hooks")
    parser.add_argument("--claude", action="store_true", help="Install Claude Code commands, skills & memory pointer")
    parser.add_argument("--agents", action="store_true", help="Ensure AGENTS.md canonical rules pointer")
    parser.add_argument("--clean", action="store_true", help="Remove all generated assistant artifacts")
    parser.add_argument("-w", "--wizard", action="store_true", help="Run interactive setup wizard")
    parser.add_argument("--binary-mode", action="store_true", help=argparse.SUPPRESS)
    parser.add_argument("-y", "--yes", action="store_true", help="Automatically accept insert-only pointer injection prompts")

    gitignore_group = parser.add_mutually_exclusive_group()
    gitignore_group.add_argument(
        "--gitignore",
        dest="gitignore",
        action="store_true",
        default=None,
        help="Add installed tooling files and generated artifacts to .gitignore",
    )
    gitignore_group.add_argument(
        "--no-gitignore",
        dest="gitignore",
        action="store_false",
        default=None,
        help="Do not add installed tooling files to .gitignore (skip prompt)",
    )

    parser.add_argument("--root-dir", default=".", help="Root repository path (default: .)")

    args = parser.parse_args(argv)
    root_dir = Path(args.root_dir).resolve()

    if args.clean:
        clean_tooling(root_dir)
        return 0

    if not (root_dir / ".git").exists():
        print(
            f"⚠️  Warning: Target directory '{root_dir}' is not a Git-initialized repository (.git directory not found)."
        )
        print(
            "   Git pre-commit hooks cannot be installed until you run 'git init' and re-run initialization."
        )

    is_binary_mode = bool(
        args.binary_mode
        or getattr(sys, "frozen", False)
        or (sys.argv and sys.argv[0].endswith(".pyz"))
    )

    specific_requested = args.git_hook or args.antigravity or args.claude or args.agents
    bootstrap_workspace_templates(
        root_dir,
        overwrite=False,
        include_env_example=is_binary_mode,
    )

    wizard_gitignore: bool | None = None
    if args.wizard or (
        is_binary_mode
        and not specific_requested
        and not args.all
        and not args.yes
        and _is_interactive_or_mocked()
    ):
        selection, wizard_gitignore = run_init_wizard(
            root_dir,
            ask_gitignore=(args.gitignore is None),
        )
        install_all = selection["all"]
        do_antigravity = selection["antigravity"]
        do_claude = selection["claude"]
        do_agents = selection["agents"]
    else:
        install_all = args.all or not specific_requested
        do_antigravity = args.antigravity
        do_claude = args.claude
        do_agents = args.agents

    existing_agents = find_existing_file(root_dir, ("AGENTS.md", "agents.md"))
    had_non_empty_agents = bool(
        existing_agents and existing_agents.is_file() and existing_agents.read_text(encoding="utf-8").strip()
    )

    if install_all:
        install_git_hook(root_dir)
        install_antigravity(root_dir)
        ensure_agents_file(root_dir, assume_yes=args.yes)
        install_claude(root_dir, assume_yes=args.yes)
    else:
        # Always ensure the Git pre-commit hook is installed when configuring any specific agent or hook
        install_git_hook(root_dir)
        if do_antigravity:
            install_antigravity(root_dir)
        if do_agents:
            ensure_agents_file(root_dir, assume_yes=args.yes)
        if do_claude:
            install_claude(root_dir, assume_yes=args.yes)

    # Trigger dynamic organizational rules sync only when ORG_RULES_SYNC_URL is configured
    load_dotenv(root_dir)
    raw_sync_url = os.getenv("ORG_RULES_SYNC_URL", "").strip()
    if raw_sync_url:
        try:
            synced = sync_org_rules(root_dir=root_dir, force=True)
            if synced:
                active_count = len(get_local_rules(root_dir))
                print(f"✅ Synchronized {active_count} organizational rule(s) from ORG_RULES_SYNC_URL.")
            else:
                print("⚠️  Could not reach ORG_RULES_SYNC_URL during init; run 'agentic-dev sync' when online.")
        except Exception:
            pass
    elif is_binary_mode and not get_local_rules(root_dir):
        print(
            "ℹ️  No ORG_RULES_SYNC_URL configured in .env; skipped remote organizational rules sync. "
            "(Set ORG_RULES_SYNC_URL in .env and run 'agentic-dev sync')"
        )

    if args.gitignore is not None:
        should_gitignore = args.gitignore
    elif wizard_gitignore is not None:
        should_gitignore = wizard_gitignore
    else:
        should_gitignore = ask_gitignore_preference(binary_mode=is_binary_mode)

    if should_gitignore:
        created_new_agents = (install_all or do_agents) and not had_non_empty_agents
        update_gitignore(
            root_dir,
            include_antigravity=install_all or do_antigravity,
            include_claude=install_all or do_claude,
            include_agents_md=created_new_agents,
            include_scripts=not is_binary_mode,
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
