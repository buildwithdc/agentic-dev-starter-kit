    # Clean AGENTS.md / agents.md
    agents_file = find_existing_file(root_dir, ("AGENTS.md", "agents.md"))
    if agents_file and agents_file.exists():
        content = agents_file.read_text(encoding="utf-8")
        if "BEGIN CANONICAL RULES POINTER" in content:
            cleaned = strip_pointer_block(content)
