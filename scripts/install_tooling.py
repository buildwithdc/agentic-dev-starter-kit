    claude_file = find_existing_file(root_dir, ("CLAUDE.md", "claude.md"))
    if claude_file and claude_file.exists():
        content = claude_file.read_text(encoding="utf-8")
        if "BEGIN CANONICAL RULES POINTER" in content:
            cleaned = strip_pointer_block(content)
            if cleaned.strip() in ("", "# Claude Memory"):
                claude_file.unlink()
                print(f"🗑️  Removed {claude_file.name}")
            else:
                claude_file.write_text(cleaned, encoding="utf-8")
