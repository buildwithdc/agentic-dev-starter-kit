def find_existing_file(root_dir: Path, candidates: tuple[str, ...]) -> Path | None:
    """Find the first matching candidate file in root_dir (case-insensitive check)."""
    for name in candidates:
        candidate_path = root_dir / name
        if candidate_path.is_file():
            return candidate_path

    candidates_lower = {c.lower(): c for c in candidates}
    try:
        for entry in root_dir.iterdir():
            if entry.is_file() and entry.name.lower() in candidates_lower:
                return entry
    except OSError:
        pass
    return None


def ask_permission(file_path: Path, assume_yes: bool = False) -> bool:
    """Prompt the user for permission to inject canonical rules pointer.

    Notifies the user that this is an insert-only operation.
    """
    if assume_yes:
        return True

    print(f"\n📄 Found existing non-empty file: {file_path.name}")
    print("ℹ️  Note: This is an insert-only operation that appends the canonical rules pointer without modifying or overwriting your existing content.")

    if not _is_interactive_or_mocked():
        print(f"⚠️  Non-interactive terminal detected. Skipping pointer injection into {file_path.name}. (Use -y/--yes to accept)")
        return False

    try:
        response = input(f"Do you grant permission to add the rules pointer to {file_path.name}? [y/N]: ").strip().lower()
        return response in ("y", "yes")
    except (EOFError, KeyboardInterrupt):
        print("\nOperation cancelled by user.")
        return False


