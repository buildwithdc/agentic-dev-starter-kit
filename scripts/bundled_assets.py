#!/usr/bin/env python3
"""Workspace template bootstrapper for standalone binary / zipapp.

Creates the 3-tier `.agents/rules/{org,team,personal}` directory hierarchy and
manages `.env.example` / `.env` configuration templates using non-destructive
tagged blocks (`# BEGIN AGENTIC DEV ENV` ... `# END AGENTIC DEV ENV`) with
key-level collision detection.
"""

from __future__ import annotations

import re
import sys
import zipfile
from pathlib import Path

try:
    from scripts.constants import (
        ORG_TIER_DIR_NAME,
        PERSONAL_TIER_DIR_NAME,
        RULES_DIR_NAME,
        TEAM_TIER_DIR_NAME,
    )
except ImportError:
    from constants import (
        ORG_TIER_DIR_NAME,
        PERSONAL_TIER_DIR_NAME,
        RULES_DIR_NAME,
        TEAM_TIER_DIR_NAME,
    )

ENV_EXAMPLE_FILENAME = ".env.example"
ENV_FILENAME = ".env"

ENV_BLOCK_START_TAG = "# BEGIN AGENTIC DEV ENV (Auto-generated by agentic-dev)"
ENV_BLOCK_END_TAG = "# END AGENTIC DEV ENV"

DEFAULT_ENV_EXAMPLE_CONTENT = """# Gemini API Configuration for LLM-powered pre-commit reviews & code auditor
# GEMINI_API_KEY is optional: if unset, the reviewer automatically tries Google ADC (gcloud auth application-default login)
# GEMINI_API_KEY=your_gemini_api_key_here
GEMINI_MODEL=gemini-3.8-flash
GOOGLE_CLOUD_LOCATION=global
GEMINI_TIMEOUT=30.0
GEMINI_DEP_DEPTH=1
GEMINI_MAX_DEP_CHARS=24000

# Central Organizational Rules Synchronization URL (Release bundle zip, tag URL, or repository archive)
# Reference implementation: https://github.com/buildwithdc/sample-agentic-dev-governance-rules
# ORG_RULES_SYNC_URL="https://github.com/buildwithdc/sample-agentic-dev-governance-rules/releases/latest/download/rules-org.zip"
"""

_ENV_KEY_PATTERN = re.compile(r"^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$")
_COMMENTED_ENV_KEY_PATTERN = re.compile(r"^#\s*([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$")


def _find_zipapp_archive() -> Path | None:
    """Detect if running inside a .pyz zipapp archive and return its Path."""
    loader = globals().get("__loader__")
    archive = getattr(loader, "archive", None)
    if archive:
        cand = Path(str(archive))
        if cand.is_file() and zipfile.is_zipfile(cand):
            return cand

    if sys.argv and sys.argv[0]:
        argv0 = Path(sys.argv[0])
        if argv0.is_file() and argv0.suffix == ".pyz" and zipfile.is_zipfile(argv0):
            return argv0

    return None


def load_env_example_template() -> str:
    """Load `.env.example` template from PyInstaller _MEIPASS, .pyz zipapp, source root, or default."""
    content = DEFAULT_ENV_EXAMPLE_CONTENT

    try:
        source_root = Path(__file__).resolve().parent.parent
        candidate = source_root / ENV_EXAMPLE_FILENAME
        if candidate.is_file():
            content = candidate.read_text(encoding="utf-8")
    except OSError:
        pass

    zip_archive = _find_zipapp_archive()
    if zip_archive is not None:
        try:
            with zipfile.ZipFile(zip_archive, "r") as zf:
                if ENV_EXAMPLE_FILENAME in zf.namelist():
                    content = zf.read(ENV_EXAMPLE_FILENAME).decode("utf-8")
        except Exception:
            pass

    meipass = getattr(sys, "_MEIPASS", None)
    if meipass:
        candidate = Path(str(meipass)) / ENV_EXAMPLE_FILENAME
        if candidate.is_file():
            try:
                content = candidate.read_text(encoding="utf-8")
            except OSError:
                pass

    return strip_env_block(content) if ENV_BLOCK_START_TAG in content else content


def strip_env_block(content: str) -> str:
    """Remove the managed `# BEGIN AGENTIC DEV ENV` block if present."""
    start_idx = content.find(ENV_BLOCK_START_TAG)
    end_idx = content.find(ENV_BLOCK_END_TAG)
    if start_idx != -1 and end_idx != -1 and end_idx >= start_idx:
        cleaned = content[:start_idx] + content[end_idx + len(ENV_BLOCK_END_TAG) :]
        return cleaned.strip() + ("\n" if cleaned.strip() else "")
    return content


def _extract_active_env_keys(content: str) -> dict[str, str]:
    """Extract active (uncommented) KEY=VALUE pairs from env content."""
    keys: dict[str, str] = {}
    for line in content.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        match = _ENV_KEY_PATTERN.match(stripped)
        if match:
            keys[match.group(1)] = match.group(2).strip()
    return keys


def _extract_existing_block_body(content: str) -> str:
    """Return the inner text of an existing `# BEGIN AGENTIC DEV ENV` block if present."""
    start_idx = content.find(ENV_BLOCK_START_TAG)
    end_idx = content.find(ENV_BLOCK_END_TAG)
    if start_idx == -1 or end_idx == -1 or end_idx < start_idx:
        return ""
    return content[start_idx + len(ENV_BLOCK_START_TAG) : end_idx].strip()


def merge_env_file(
    target_file: Path,
    overrides: dict[str, str] | None = None,
    overwrite: bool = False,
) -> tuple[bool, list[str]]:
    """Create or non-destructively merge the agentic-dev env block into `target_file`.

    - If `target_file` does not exist or `overwrite=True`, writes the template wrapped in
      `ENV_BLOCK_START_TAG` ... `ENV_BLOCK_END_TAG`.
    - If `target_file` already exists:
      * Preserves all user lines outside the managed block.
      * Detects any keys already defined in the user's section (`colliding_keys`) and
        comments them out inside the managed block so existing user values are NEVER overridden.
      * Preserves any values previously customized inside the managed block unless overridden
        via `overrides`.

    Returns:
        `(modified: bool, colliding_keys: list[str])`
    """
    template_body = load_env_example_template().strip()
    existing_text = target_file.read_text(encoding="utf-8") if target_file.is_file() else ""

    if overwrite or not existing_text.strip():
        lines = _apply_block_overrides_and_collisions(
            template_body,
            overrides=overrides or {},
            user_keys={},
            previous_block_keys={},
        )
        block = f"{ENV_BLOCK_START_TAG}\n" + "\n".join(lines) + f"\n{ENV_BLOCK_END_TAG}\n"
        target_file.parent.mkdir(parents=True, exist_ok=True)
        target_file.write_text(block, encoding="utf-8")
        return True, []

    # Check if the file already has the managed block and no new overrides are requested
    has_block = ENV_BLOCK_START_TAG in existing_text and ENV_BLOCK_END_TAG in existing_text
    if has_block and not overrides:
        return False, []

    base_user_content = strip_env_block(existing_text).rstrip()
    user_keys = _extract_active_env_keys(base_user_content)
    prev_block_body = _extract_existing_block_body(existing_text)
    prev_block_keys = _extract_active_env_keys(prev_block_body)

    # If the existing file is an exact copy of raw .env.example (without block tags),
    # treat its keys as previous block keys rather than external user collisions
    if not has_block and base_user_content.strip() == template_body:
        base_user_content = ""
        prev_block_keys = user_keys
        user_keys = {}

    colliding_keys: list[str] = []
    for line in template_body.splitlines():
        stripped = line.strip()
        m_active = _ENV_KEY_PATTERN.match(stripped)
        m_comm = _COMMENTED_ENV_KEY_PATTERN.match(stripped)
        key_name = m_active.group(1) if m_active else (m_comm.group(1) if m_comm else None)
        if key_name and key_name in user_keys and key_name not in colliding_keys:
            colliding_keys.append(key_name)

    # If user explicitly passed an override for a key that already exists in base_user_content,
    # update it in base_user_content in-place so we don't create duplicate keys
    if overrides and base_user_content:
        updated_user_lines: list[str] = []
        for line in base_user_content.splitlines():
            m = _ENV_KEY_PATTERN.match(line.strip())
            if m and m.group(1) in overrides:
                k = m.group(1)
                updated_user_lines.append(f"{k}={overrides[k]}")
            else:
                updated_user_lines.append(line)
        base_user_content = "\n".join(updated_user_lines)

    block_lines = _apply_block_overrides_and_collisions(
        template_body,
        overrides=overrides or {},
        user_keys=user_keys,
        previous_block_keys=prev_block_keys,
    )
    block_text = f"{ENV_BLOCK_START_TAG}\n" + "\n".join(block_lines) + f"\n{ENV_BLOCK_END_TAG}"
    new_content = f"{base_user_content}\n\n{block_text}\n" if base_user_content else f"{block_text}\n"

    if new_content == existing_text:
        return False, colliding_keys

    target_file.parent.mkdir(parents=True, exist_ok=True)
    target_file.write_text(new_content, encoding="utf-8")
    return True, colliding_keys


def _apply_block_overrides_and_collisions(
    template_body: str,
    overrides: dict[str, str],
    user_keys: dict[str, str],
    previous_block_keys: dict[str, str],
) -> list[str]:
    """Render lines inside the managed block, applying overrides and commenting out colliding user keys."""
    rendered: list[str] = []
    handled_overrides: set[str] = set()

    for line in template_body.splitlines():
        stripped = line.strip()
        m_active = _ENV_KEY_PATTERN.match(stripped)
        m_comm = _COMMENTED_ENV_KEY_PATTERN.match(stripped)

        if m_active:
            key = m_active.group(1)
            if key in user_keys:
                rendered.append(f"# {key}={m_active.group(2)}  # (preserved existing value above)")
                handled_overrides.add(key)
            elif key in overrides:
                rendered.append(f"{key}={overrides[key]}")
                handled_overrides.add(key)
            elif key in previous_block_keys:
                rendered.append(f"{key}={previous_block_keys[key]}")
            else:
                rendered.append(line)
        elif m_comm:
            key = m_comm.group(1)
            if key in user_keys:
                rendered.append(f"# {key}={m_comm.group(2)}  # (preserved existing value above)")
                handled_overrides.add(key)
            elif key in overrides:
                rendered.append(f"{key}={overrides[key]}")
                handled_overrides.add(key)
            elif key in previous_block_keys:
                rendered.append(f"{key}={previous_block_keys[key]}")
            else:
                rendered.append(line)
        else:
            rendered.append(line)

    for key, val in overrides.items():
        if key not in handled_overrides and key not in user_keys:
            rendered.append(f"{key}={val}")

    return rendered


def bootstrap_workspace_templates(
    root_dir: Path | str,
    overwrite: bool = False,
    include_env_example: bool = True,
) -> list[str]:
    """Initialize 3-tier `.agents/rules/{org,team,personal}` directories and `.env.example`.

    Does NOT create static rule markdown files (Tier 1 `org/` rules are synced dynamically
    from `ORG_RULES_SYNC_URL` via `sync_org_rules.py`, and Tier 2 `team/` rules live in the target repo).
    If `.env.example` already exists in `root_dir`, merges the managed `# BEGIN AGENTIC DEV ENV`
    block without overwriting existing project variables.
    Returns list of relative file paths created or updated.
    """
    root = Path(root_dir).resolve()
    rules_dir = root / RULES_DIR_NAME
    (rules_dir / ORG_TIER_DIR_NAME).mkdir(parents=True, exist_ok=True)
    (rules_dir / TEAM_TIER_DIR_NAME).mkdir(parents=True, exist_ok=True)
    personal_dir = rules_dir / PERSONAL_TIER_DIR_NAME
    personal_dir.mkdir(parents=True, exist_ok=True)
    gitkeep = personal_dir / ".gitkeep"
    if not gitkeep.exists():
        gitkeep.touch()

    written: list[str] = []
    if include_env_example:
        target = root / ENV_EXAMPLE_FILENAME
        modified, _ = merge_env_file(target, overwrite=overwrite)
        if modified:
            written.append(ENV_EXAMPLE_FILENAME)

    return written
